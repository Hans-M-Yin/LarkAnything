import { _electron as electron } from 'playwright';
import { mkdir, writeFile, copyFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import assert from 'node:assert/strict';
const root = resolve('.larkanything/desktop-smoke');
const vault = join(root, 'vault');
const codexHome = join(root, 'codex');
const claudeHome = join(root, 'claude');
await mkdir(vault, { recursive: true });
await mkdir(join(codexHome, 'sessions'), { recursive: true });
await mkdir(join(claudeHome, 'projects'), { recursive: true });
await copyFile('examples/codex.jsonl', join(codexHome, 'sessions/sample.jsonl'));
await writeFile(join(vault, '灵感收集.md'), '# 灵感收集\n\n把值得留下的想法，整理到同一个地方。\n\n- 一段有价值的对话\n- 一篇正在完善的笔记\n\n```js\nconst idea = "Keep it simple";\n```');
await writeFile(join(root, 'desktop.json'), JSON.stringify({ vault, codexHome, claudeHome }));
await writeFile(join(root, 'config.json'), JSON.stringify({ version: 1, stateDir: 'state' }));
const env = { ...process.env, LARKANYTHING_DESKTOP_HOME: root }; delete env.ELECTRON_RUN_AS_NODE;
const app = await electron.launch({ args: ['desktop/main.mjs', `--user-data-dir=${join(root, 'electron')}`], env, timeout: 30000 });
try {
  const page = await app.firstWindow();
  await page.addInitScript(() => localStorage.setItem('la-setup-dismissed', '1'));
  await page.reload();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.locator('.item').first().waitFor({ timeout: 60000 });
  await page.evaluate(() => { localStorage.setItem('la-theme', 'light'); });
  await page.reload();
  await page.locator('.item').first().waitFor();
  await page.screenshot({ animations: 'disabled', scale: 'css', path: join(root, 'home.png') });
  assert.ok(await page.locator('.source img').evaluateAll(images => images.every(img => img.complete && img.naturalWidth > 0)), 'Source icons must load offline');
  await page.getByRole('button', { name: 'Claude Code', exact: true }).click();
  await page.getByText('这里还没有内容', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Codex', exact: true }).click();
  await page.getByRole('textbox', { name: '搜索内容' }).fill('no-matching-fixture');
  await page.getByText('没有匹配的内容', { exact: true }).waitFor();
  await page.getByRole('textbox', { name: '搜索内容' }).fill('');
  await page.locator('.item').first().click();
  assert.equal(await page.locator('iframe').count(), 0);
  assert.equal(await page.evaluate(() => innerWidth), 420);
  await page.getByRole('button', { name: '预览', exact: true }).click();
  assert.equal(await page.evaluate(() => innerWidth), 860);
  await page.locator('iframe').waitFor();
  // Text can exist in an opaque-origin frame while Electron paints it blank.
  // Assert layout before taking screenshots (which may force a repaint).
  await page.frameLocator('iframe').locator('article').waitFor({ state: 'visible' });
  assert.ok(await page.frameLocator('iframe').locator('body').evaluate(el => el.offsetWidth > 0 && el.scrollHeight > 0));
  assert.match(await page.frameLocator('iframe').locator('body').innerText(), /用户|Codex/);
  await page.getByRole('button', { name: 'Obsidian', exact: true }).click();
  await page.getByRole('button').filter({ hasText: '灵感收集' }).click();
  await page.locator('iframe').waitFor();
  assert.match(await page.frameLocator('iframe').locator('body').innerText(), /Keep it simple/);
  await page.frameLocator('iframe').locator('article').waitFor({ state: 'visible' });
  await page.screenshot({ animations: 'disabled', scale: 'css', path: join(root, 'preview.png') });
  await page.getByRole('button', { name: '切换深色模式', exact: true }).click();
  await page.frameLocator('iframe').getByText('Keep it simple', { exact: false }).waitFor();
  assert.equal(await page.frameLocator('iframe').locator('body').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(32, 32, 32)');
  await page.screenshot({ animations: 'disabled', scale: 'css', path: join(root, 'dark.png') });
  await page.getByRole('button', { name: '切换浅色模式', exact: true }).click();
  await page.getByRole('button', { name: '收起预览', exact: true }).first().click();
  assert.equal(await page.evaluate(() => innerWidth), 420);
  await page.screenshot({ animations: 'disabled', scale: 'css', path: join(root, 'compact-selected.png') });
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.getByLabel('飞书保存位置').fill('discard-me');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: '设置', exact: true }).click();
  assert.equal(await page.getByLabel('飞书保存位置').inputValue(), '');
  await page.getByLabel('飞书保存位置').fill('https://example.feishu.cn/drive/folder/demo123');
  await page.screenshot({ animations: 'disabled', scale: 'css', path: join(root, 'settings.png') });
  await page.getByRole('button', { name: '保存设置', exact: true }).click();
  await page.getByRole('button').filter({ hasText: '灵感收集' }).click();
  await page.locator('footer strong').filter({ hasText: 'demo123' }).waitFor();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await page.locator('.source').first().evaluate(el => getComputedStyle(el).transitionDuration), '0s');
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(380, 480));
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.getByRole('button', { name: '设置', exact: true }).click();
  assert.ok(await page.getByRole('button', { name: '保存设置', exact: true }).isVisible());
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: '预览', exact: true }).click();
  await page.locator('iframe').evaluate(el => { el.srcdoc = '<html><body><article>Sandbox probe</article><script>window.previewScriptExecuted=true;parent.document.body.dataset.previewScriptExecuted="yes"</script></body></html>'; });
  await page.frameLocator('iframe').getByText('Sandbox probe').waitFor({ state: 'visible' });
  assert.equal(await page.frameLocator('iframe').locator('body').evaluate(() => window.previewScriptExecuted), undefined);
  assert.equal(await page.locator('body').getAttribute('data-preview-script-executed'), null);
  assert.deepEqual(errors, []);
  console.log('Electron smoke passed: source icons, search/empty states, Core previews, light/dark, cancelled/saved settings, destination, reduced motion, compact window. No remote writes.');
} finally { await app.close(); }
